"""
VERONIKA AI - Exam Predictor (Phase 3)

The exam-mentor side of VERONIKA: given a subject, a syllabus and a bank of
past questions, it predicts the highest-probability topics and likely exam
questions, plus a marks-maximising strategy.

  - Past questions are persisted in memory (category "exam_past_questions").
  - Predictions are generated by the provider; if the model is unavailable it
    falls back to a transparent frequency/recency heuristic over past papers.
  - Predictions can be saved (category "exam_predictions") for later review.

It complements the `exam_mentor` relationship overlay in `ai.entity_manager`.
"""
import json
import logging
import re
from dataclasses import dataclass, field
from datetime import datetime
from typing import Dict, List, Optional

logger = logging.getLogger(__name__)

PAST_QUESTIONS_CATEGORY = "exam_past_questions"
PREDICTIONS_CATEGORY = "exam_predictions"

# Subject-generic stopwords for the heuristic fallback.
_STOPWORDS = {
    "the", "a", "an", "of", "and", "or", "to", "in", "on", "for", "with", "is",
    "are", "was", "were", "what", "why", "how", "which", "that", "this", "explain",
    "define", "describe", "write", "short", "note", "notes", "discuss", "state",
    "evaluate", "give", "example", "examples", "difference", "between", "using",
    "its", "it", "as", "by", "be", "from",
}

_EXAM_PROMPT = """You are the exam-prediction module of VERONIKA AI, acting as a strict
exam mentor. Predict the most likely topics and questions for an upcoming exam.

Subject: {subject}
Syllabus / topic list: {syllabus}
Past questions observed: {past}

Reply with EXACTLY ONE JSON object and nothing else:
{{"topics": [{{"topic": "...", "probability": 0.0, "importance": "high|medium|low", "reason": "..."}}],
  "questions": ["...", "..."],
  "strategy": "marks-maximising study strategy in 1-3 sentences"}}

Rules:
- Give at most {num_topics} topics, ordered by probability (0.0-1.0, most likely first).
- Give at most {num_questions} likely questions, most probable first.
- Base probabilities on syllabus weightage and the frequency of past questions.
- Be concrete and specific to the subject.
"""


# ═══════════════════════════════════════════════════════════════
# Data models
# ═══════════════════════════════════════════════════════════════

@dataclass
class PredictedTopic:
    topic: str
    probability: float = 0.0
    importance: str = "medium"
    reason: str = ""

    def to_dict(self) -> dict:
        return {
            "topic": self.topic,
            "probability": round(self.probability, 3),
            "importance": self.importance,
            "reason": self.reason,
        }


@dataclass
class ExamPrediction:
    subject: str
    topics: List[PredictedTopic] = field(default_factory=list)
    questions: List[str] = field(default_factory=list)
    strategy: str = ""
    source: str = "ai"              # "ai" | "heuristic"
    generated_at: str = ""

    def summary(self) -> str:
        lines = [f"Exam prediction for {self.subject} ({self.source}):"]
        for i, t in enumerate(self.topics, 1):
            pct = int(round(t.probability * 100))
            lines.append(f"  {i}. {t.topic} — {pct}% [{t.importance}]")
        if self.questions:
            lines.append("Likely questions:")
            for i, q in enumerate(self.questions, 1):
                lines.append(f"  {i}. {q}")
        if self.strategy:
            lines.append(f"Strategy: {self.strategy}")
        return "\n".join(lines)

    def to_dict(self) -> dict:
        return {
            "subject": self.subject,
            "source": self.source,
            "generated_at": self.generated_at,
            "strategy": self.strategy,
            "topics": [t.to_dict() for t in self.topics],
            "questions": list(self.questions),
        }


# ═══════════════════════════════════════════════════════════════
# Predictor
# ═══════════════════════════════════════════════════════════════

class ExamPredictor:
    """Predicts exam topics/questions using the provider + memory bank."""

    def __init__(self, provider_manager=None, memory_manager=None):
        if provider_manager is None:
            try:
                from ai.provider_manager import ProviderManager
                provider_manager = ProviderManager()
            except Exception:
                provider_manager = None
        self.provider_manager = provider_manager
        self.memory_manager = memory_manager

    # ── Past-question bank ────────────────────────────────────

    @staticmethod
    def _norm(subject: str) -> str:
        return (subject or "").strip().lower()

    def get_past_questions(self, subject: str) -> List[dict]:
        if not self.memory_manager:
            return []
        raw = None
        try:
            raw = self.memory_manager.recall_memory(PAST_QUESTIONS_CATEGORY, self._norm(subject))
        except Exception as e:  # noqa: BLE001
            logger.debug("recall past questions failed: %s", e)
        if not raw:
            return []
        try:
            data = json.loads(raw)
            return data if isinstance(data, list) else []
        except (json.JSONDecodeError, TypeError):
            return []

    def add_past_question(self, subject: str, question: str,
                          year: str = "", marks: int = 0) -> dict:
        """Append a past question to the subject's bank (persists to memory)."""
        entry = {"question": question, "year": year, "marks": marks}
        items = self.get_past_questions(subject)
        items.append(entry)
        if self.memory_manager:
            try:
                self.memory_manager.save_memory(
                    PAST_QUESTIONS_CATEGORY, self._norm(subject), json.dumps(items)
                )
            except Exception as e:  # noqa: BLE001
                logger.warning("Failed to persist past question: %s", e)
        return entry

    def list_subjects(self) -> List[str]:
        if not self.memory_manager:
            return []
        try:
            records = self.memory_manager.get_all_memories(PAST_QUESTIONS_CATEGORY)
        except Exception:
            return []
        return [r.get("key", "") for r in records if r.get("key")]

    # ── Prediction ────────────────────────────────────────────

    def predict(
        self,
        subject: str,
        syllabus: str = "",
        num_topics: int = 8,
        num_questions: int = 10,
    ) -> ExamPrediction:
        past = self.get_past_questions(subject)
        prediction = self._ai_predict(subject, syllabus, past, num_topics, num_questions)
        if prediction is None:
            prediction = self._heuristic_predict(subject, past, num_topics, num_questions)
        prediction.generated_at = datetime.now().isoformat()
        return prediction

    def _ai_predict(self, subject, syllabus, past, num_topics, num_questions) -> Optional[ExamPrediction]:
        if self.provider_manager is None:
            return None
        past_text = "; ".join(p.get("question", "") for p in past[:30]) or "(none recorded)"
        prompt = _EXAM_PROMPT.format(
            subject=subject,
            syllabus=syllabus or "(not provided)",
            past=past_text,
            num_topics=num_topics,
            num_questions=num_questions,
        )
        try:
            resp = self.provider_manager.send_message(prompt)
        except Exception as e:  # noqa: BLE001
            logger.debug("Exam prediction provider error: %s", e)
            return None
        if getattr(resp, "is_error", False):
            return None
        data = _extract_json(getattr(resp, "content", "") or "")
        if not data:
            return None
        return self._parse_prediction(subject, data, "ai", num_topics, num_questions)

    @staticmethod
    def _parse_prediction(subject, data, source, num_topics, num_questions) -> ExamPrediction:
        topics: List[PredictedTopic] = []
        for t in (data.get("topics") or [])[:num_topics]:
            if not isinstance(t, dict):
                continue
            try:
                prob = float(t.get("probability", 0.0))
            except (TypeError, ValueError):
                prob = 0.0
            prob = max(0.0, min(1.0, prob))
            topics.append(PredictedTopic(
                topic=str(t.get("topic", "")).strip(),
                probability=prob,
                importance=str(t.get("importance", "medium")).lower(),
                reason=str(t.get("reason", "")).strip(),
            ))
        questions = [str(q).strip() for q in (data.get("questions") or [])[:num_questions] if str(q).strip()]
        return ExamPrediction(
            subject=subject,
            topics=[t for t in topics if t.topic],
            questions=questions,
            strategy=str(data.get("strategy", "")).strip(),
            source=source,
        )

    @staticmethod
    def _heuristic_predict(subject, past, num_topics, num_questions) -> ExamPrediction:
        """Frequency/recency heuristic over past questions (no model needed)."""
        freq: Dict[str, int] = {}
        for p in past:
            q = p.get("question", "")
            for word in re.findall(r"[A-Za-z][A-Za-z\-]{3,}", q.lower()):
                if word in _STOPWORDS:
                    continue
                freq[word] = freq.get(word, 0) + 1

        ranked = sorted(freq.items(), key=lambda kv: (-kv[1], kv[0]))[:num_topics]
        total = sum(c for _, c in ranked) or 1
        topics = [
            PredictedTopic(
                topic=word,
                probability=round(count / total, 3),
                importance="high" if i < max(1, num_topics // 3) else "medium",
                reason=f"appears {count}x in past questions",
            )
            for i, (word, count) in enumerate(ranked)
        ]
        questions = [p.get("question", "") for p in past[-num_questions:]][::-1]
        strategy = (
            "Model unavailable — heuristic ranking based on past-question frequency. "
            "Drill the top recurring topics first."
            if past else
            "No past questions recorded and the model is unavailable. "
            "Add past questions or configure a provider for real predictions."
        )
        return ExamPrediction(
            subject=subject, topics=topics, questions=questions,
            strategy=strategy, source="heuristic",
        )

    # ── Persistence ───────────────────────────────────────────

    def save_prediction(self, prediction: ExamPrediction):
        if not self.memory_manager:
            return
        try:
            self.memory_manager.save_memory(
                PREDICTIONS_CATEGORY,
                self._norm(prediction.subject),
                json.dumps(prediction.to_dict()),
            )
        except Exception as e:  # noqa: BLE001
            logger.warning("Failed to save exam prediction: %s", e)


def _extract_json(text: str) -> dict:
    if not text:
        return {}
    for block in re.findall(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL):
        try:
            obj = json.loads(block)
            if isinstance(obj, dict):
                return obj
        except json.JSONDecodeError:
            continue
    decoder = json.JSONDecoder()
    pos = 0
    while pos < len(text):
        idx = text.find("{", pos)
        if idx == -1:
            break
        try:
            obj, _ = decoder.raw_decode(text[idx:])
            if isinstance(obj, dict):
                return obj
        except json.JSONDecodeError:
            pass
        pos = idx + 1
    return {}
